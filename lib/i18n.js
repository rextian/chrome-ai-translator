  const SUPPORTED = ['zh-CN', 'zh-TW', 'ja', 'ko', 'en'];

  function detect(pref) {
    if (SUPPORTED.includes(pref)) return pref;
    const nav = ((typeof navigator !== 'undefined' && navigator.language) || 'zh-CN').toLowerCase();
    if (nav.startsWith('zh')) {
      // 繁体场景：zh-TW / zh-HK / zh-MO / zh-Hant*
      return /tw|hk|mo|hant/.test(nav) ? 'zh-TW' : 'zh-CN';
    }
    if (nav.startsWith('ja')) return 'ja';
    if (nav.startsWith('ko')) return 'ko';
    return 'en';
  }

  /**
   * 取文案：t('auto', 'progress', {done: 3, total: 10})
   * 未命中键回退到中文，再回退到键名
   */
  function t(langPref, key, vars) {
    const lang = detect(langPref);
    let s = (MESSAGES[lang] && MESSAGES[lang][key]) ?? MESSAGES['zh-CN'][key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        s = s.replaceAll('{' + k + '}', String(v));
      }
    }
    return s;
  }

  g.AI_TR_I18N = { MESSAGES, detect, t };
